#!/usr/bin/env python3
"""Assemble a self-contained GitHub Pages app from the tested C++ WASM build."""

from __future__ import annotations

import argparse
import hashlib
import html
import json
from pathlib import Path
import shutil
import subprocess
import tempfile
from urllib.parse import quote

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor

ROOT = Path(__file__).resolve().parents[1]
MARKER = ".robotwar-site-build"


class DocumentLinks(Treeprocessor):
    def run(self, root):
        for link in root.iter("a"):
            target = link.get("href", "")
            if target and not target.startswith(("#", "/", "http:", "https:", "mailto:")):
                link.set("href", "./docs/" + target)


class InlineDocumentation(Extension):
    def extendMarkdown(self, parser):
        parser.treeprocessors.register(DocumentLinks(parser), "document_links", 1)


def build(wasm_dir: Path, output: Path) -> None:
    wasm_dir, output = wasm_dir.resolve(), output.resolve()
    source = ROOT / "web"
    if output == ROOT or ROOT.is_relative_to(output) or output.is_relative_to(source):
        raise ValueError("Site output must not overwrite repository sources")
    if output.exists() and not (output / MARKER).is_file():
        raise ValueError(f"Refusing to replace an unrecognized output directory: {output}")
    for name in ("robotwar.js", "robotwar.wasm"):
        if not (wasm_dir / name).is_file():
            raise ValueError(f"Missing WASM build artifact: {wasm_dir / name}")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".robotwar-site-", dir=output.parent) as temporary:
        staging = Path(temporary) / "site"
        shutil.copytree(source, staging)
        reference = markdown.markdown(
            (source / "docs/language.md").read_text(encoding="utf-8"),
            extensions=["fenced_code", "tables", "toc", "sane_lists", InlineDocumentation()],
            extension_configs={"toc": {"permalink": False}},
        )
        brief = (source / "docs/agent-brief.txt").read_text(encoding="utf-8")
        index = (source / "index.html").read_text(encoding="utf-8")
        for marker, content in (("<!-- LANGUAGE_REFERENCE -->", reference),
                                ("<!-- AGENT_BRIEF -->", html.escape(brief))):
            if index.count(marker) != 1:
                raise ValueError(f"Expected exactly one {marker} placeholder")
            index = index.replace(marker, content)
        (staging / "index.html").write_text(index, encoding="utf-8")
        (staging / "wasm").mkdir(exist_ok=True)
        for name in ("robotwar.js", "robotwar.wasm"):
            shutil.copyfile(wasm_dir / name, staging / "wasm" / name)
        (staging / "package.json").write_text('{"type":"module","private":true}\n')
        (staging / "samples").mkdir(exist_ok=True)
        samples = []
        for path in sorted((ROOT / "robots/examples").iterdir()):
            if not path.is_file() or path.name.startswith("."):
                continue
            name = path.name + ".robot"
            shutil.copyfile(path, staging / "samples" / name)
            samples.append({"name": path.name, "path": "./samples/" + quote(name),
                            "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
        if len(samples) < 2:
            raise ValueError("The browser workbench needs at least two sample robots")
        (staging / "samples/manifest.json").write_text(json.dumps(samples, indent=2) + "\n")
        shutil.copyfile(ROOT / "docs/Robot Warriors Manual.pdf", staging / "docs/original-manual.pdf")
        revision = subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip()
        manifest = {"schema_version": 1, "revision": revision, "emscripten": "4.0.15",
                    "files": {str(path.relative_to(staging)): hashlib.sha256(path.read_bytes()).hexdigest()
                              for path in sorted(staging.rglob("*")) if path.is_file()}}
        (staging / "build-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
        (staging / ".nojekyll").touch()
        (staging / MARKER).write_text("Generated by tools/build_site.py\n")
        if output.exists():
            shutil.rmtree(output)
        staging.rename(output)
    print(f"Built {output} with {len(samples)} sample robots and embedded language documentation")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wasm-dir", type=Path, default=ROOT / "build-wasm")
    parser.add_argument("--output", type=Path, default=ROOT / "build/site")
    args = parser.parse_args()
    build(args.wasm_dir, args.output)


if __name__ == "__main__":
    main()
