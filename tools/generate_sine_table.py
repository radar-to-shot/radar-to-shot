#!/usr/bin/env python3
"""Capture the original application's sine lookup table using original ROM SANE."""
import json
import struct
from pathlib import Path
import machine68k
from oracle import OriginalMachine,A5,ROBOT,word,long
from platform_sane import RomNumericalPlatform
from generate_world_io_vectors import setup
from format_cpp import format_text
ROOT=Path(__file__).resolve().parents[1]

def main():
    m=OriginalMachine(cpu_type=machine68k.CPUType.M68030)
    try:
        platform=RomNumericalPlatform(m)
        frame=setup(m,{})
        values=[m.mem.r16s(A5-0x866+i*2) for i in range(181)]
        lines=['// Generated by tools/generate_sine_table.py from original CODE2 + IIci ROM.']
        for i in range(0,len(values),12):lines.append(', '.join(str(x) for x in values[i:i+12])+',')
        output=ROOT/'src/sine_table.inc'
        output.write_text(format_text('\n'.join(lines)+'\n',output))
        vectors=[]
        angles=list(range(-720,721))+[-32768,-32767,-1080,1080,32766,32767]
        for angle in angles:
            sine=struct.unpack('>h',m.call(3,0x30,word(angle),2))[0]
            cosine=struct.unpack('>h',m.call(3,0x9a,word(angle),2))[0]
            m.mem.w16(frame-0x12,2);m.mem.w16(frame-0x1c,angle&65535);m.call(3,0x135c,long(frame))
            result={'angle':m.mem.r16s(ROBOT+0x2076),'sin':sine,'cos':cosine}
            vectors.append({'id':f'world_trig_{len(vectors):04d}','kind':'world_trig','input':{'angle':angle},'expected':result})
        provenance=m.provenance();provenance['platform']=platform.provenance();provenance['table_values']=values
        (ROOT/'tests/golden/trig.json').write_text(json.dumps({'provenance':provenance,'vectors':vectors},indent=2)+'\n')
        print(f'Captured {len(values)} sine table entries and {len(vectors)} original trig vectors')
    finally:m.close()
if __name__=='__main__':main()
